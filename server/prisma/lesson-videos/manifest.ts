/**
 * Writes src/little-coders/videos/published-videos.ts — the list of the finished lesson videos (their
 * content hashes, sizes and chapter markers) — from what `lesson-videos:build` produced.
 *
 * Why it exists: the MP4 files are far too large for git, so they live only in the lesson-video
 * bucket. This small list is committed instead. When the server starts (or an admin presses "Check
 * storage" in the Little Coders editor) it looks for each listed video in the bucket and, if it is
 * there, shows it on its lesson. So the videos can be put into the bucket by ANY means — the bulk
 * upload tool, `rclone`, the Cloudflare dashboard — and no database access is needed to switch them on.
 *
 *   npm run lesson-videos:manifest                 reads server/.lesson-videos/manifest.json
 *   npm run lesson-videos:manifest -- --dir <dir>  reads <dir>/manifest.json
 *
 * Re-run it (and commit the result) after every rebuild of the videos: a rebuilt video has a new hash,
 * hence a new key in the bucket.
 */

import * as fs from 'fs';
import * as path from 'path';
import { LC_LESSON_SPECS } from '../../src/little-coders/curriculum';
import { lessonKey } from '../../src/little-coders/videos/narration';
import type { PublishedVideo } from '../../src/little-coders/videos/published-video';

const arg = (name: string, fallback = ''): string => {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 && process.argv[i + 1] && !process.argv[i + 1].startsWith('--')
    ? process.argv[i + 1]
    : fallback;
};

const DIR = path.resolve(
  arg(
    'dir',
    process.env.LESSON_VIDEO_OUT ||
      path.join(__dirname, '../../.lesson-videos'),
  ),
);
const TARGET = path.join(
  __dirname,
  '../../src/little-coders/videos/published-videos.ts',
);

interface BuiltInfo {
  key: string;
  durationSeconds: number;
  width: number;
  height: number;
  bytes: number;
  sha256: string;
  posterSha256?: string;
  captionsSha256?: string;
  chapters: { label: string; start: number }[];
}

function main() {
  const file = path.join(DIR, 'manifest.json');
  if (!fs.existsSync(file))
    throw new Error(
      `${file} does not exist — run "npm run lesson-videos:build" first.`,
    );
  const built = (
    JSON.parse(fs.readFileSync(file, 'utf8')) as {
      lessons: Record<string, BuiltInfo>;
    }
  ).lessons;

  const entries: PublishedVideo[] = [];
  const missing: string[] = [];
  for (const spec of LC_LESSON_SPECS) {
    const key = lessonKey(spec);
    const info = built[key];
    if (!info) {
      missing.push(key);
      continue;
    }
    entries.push({
      lesson: key,
      sha256: info.sha256,
      bytes: info.bytes,
      width: info.width,
      height: info.height,
      durationSeconds: info.durationSeconds,
      posterSha256: info.posterSha256 ?? null,
      captionsSha256: info.captionsSha256 ?? null,
      chapters: info.chapters,
    });
  }
  if (missing.length)
    throw new Error(
      `These lessons have no finished video yet: ${missing.join(', ')}. Build them first.`,
    );

  const body = entries
    .map((e) => {
      const chapters = e.chapters
        .map((c) => `{ label: ${JSON.stringify(c.label)}, start: ${c.start} }`)
        .join(', ');
      return [
        '  {',
        `    lesson: ${JSON.stringify(e.lesson)},`,
        `    sha256: ${JSON.stringify(e.sha256)},`,
        `    bytes: ${e.bytes},`,
        `    width: ${e.width},`,
        `    height: ${e.height},`,
        `    durationSeconds: ${e.durationSeconds},`,
        `    posterSha256: ${JSON.stringify(e.posterSha256)},`,
        `    captionsSha256: ${JSON.stringify(e.captionsSha256)},`,
        `    chapters: [${chapters}],`,
        '  },',
      ].join('\n');
    })
    .join('\n');

  const out = `// FILE PATH: server/src/little-coders/videos/published-videos.ts
//
// GENERATED by prisma/lesson-videos/manifest.ts (npm run lesson-videos:manifest) — do not edit by hand.
//
// The finished Little Coders lesson videos: one entry per lesson, naming each video by the SHA-256
// of its file. The files themselves are NOT in git; they are kept in the lesson-video bucket under
// the content-addressed keys these hashes give (see video-keys.ts). The server shows an entry's
// video on its lesson as soon as the matching file is in the bucket.

import type { PublishedVideo } from './published-video';

export const PUBLISHED_LESSON_VIDEOS: readonly PublishedVideo[] = [
${body}
];
`;
  fs.writeFileSync(TARGET, out);
  console.log(
    `Wrote ${entries.length} entries to ${path.relative(process.cwd(), TARGET)} (from ${file}).`,
  );
  console.log(
    'Format it with:  npx prettier --write src/little-coders/videos/published-videos.ts',
  );
}

try {
  main();
} catch (err) {
  console.error((err as Error).message);
  process.exit(1);
}
